def write_command_pages(parser) -> list[Path]:
    """Per-command page: its purpose, its real option list, and a minimal call."""
    from easyepi.cli import MINIMAL_EXAMPLE

    choices = _subparsers(parser)
    wanted = ["bam2bw", "qc", "peaks", "annotate", "tf-annotate", "dmr",
              "diff", "concordance",
              "differential-peaks", "viz"]
    written = []
    (DOCS / "commands").mkdir(parents=True, exist_ok=True)
    for name in wanted:
        sub = choices.get(name)
        if sub is None:
            continue
        rows = []
        for action in sub._actions:
            if action.dest == "help":
                continue
            flags = ", ".join(f"`{o}`" for o in action.option_strings) or action.dest
            kind = "required" if getattr(action, "required", False) else "optional"
            default = "" if action.default in (None, False) else f"`{action.default}`"
            help_text = (action.help or "").replace("|", "\\|")
            rows.append(f"| {flags} | {kind} | {default} | {help_text} |")
        example = MINIMAL_EXAMPLE.get(name, "")
        page = DOCS / "commands" / f"{name}.md"
        page.write_text("\n".join([
            f"# easyepi {name}",
            "",
            "```bash",
            example,
            "```",
            "",
            "## Options",
            "",
            "| flag | required | default | description |",
            "| --- | --- | --- | --- |",
            *rows,
            "",
            *([COMMAND_NOTES[name], ""] if name in COMMAND_NOTES else []),
            "Generated from the live parser by `scripts/gen_docs.py`.",
            "",
        ]), encoding="utf-8")
        written.append(page)
    return written


#: Prose pages may name a number of subcommands. Checked so a stale count fails the
#: build instead of sitting in the navigation beside the generated page.
COUNT_PATTERN = re.compile(r"\b(\d+)\s+subcommands\b")


def check_stale_counts(parser) -> list[str]:
    """Return complaints about any hand-written subcommand count that is wrong."""
    expected = len(_subparsers(parser))
    problems = []
    for page in sorted(DOCS.rglob("*.md")):
        text = page.read_text(encoding="utf-8")
        for lineno, line in enumerate(text.splitlines(), 1):
            for match in COUNT_PATTERN.finditer(line):
                claimed = int(match.group(1))
                if claimed != expected:
                    problems.append(
                        f"{page.relative_to(REPO)}:{lineno}: says {claimed} "
                        f"subcommands, the parser has {expected}")
    return problems


def main() -> int:
    parser = _parser()
    paths = [write_commands_index(parser)]
    paths += write_api_pages()
    paths += write_command_pages(parser)
    for p in paths:
        print("wrote", p.relative_to(REPO))
    print(f"\n{len(paths)} page(s)")

    problems = check_stale_counts(parser)
    if problems:
        for problem in problems:
            print("STALE COUNT:", problem)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
