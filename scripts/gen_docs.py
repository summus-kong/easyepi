"""Generate the MkDocs site skeleton from the real CLI.

Two reasons not to hand-write these pages:

1. **The command list must not drift.** ``commands/index.md`` is built by importing
   the parser, so a renamed flag or a new subcommand appears in the docs without
   anyone remembering to edit them.
2. **The API pages are one line each.** ``mkdocstrings`` pulls the reference out of
   the docstrings, so the only thing to generate is the stub pages that tell it which
   module to document.

Spec pages (``install.md``, ``quickstart.md``, assay pages) are written by hand --
they carry judgement that cannot be derived from code.

Run from the repository root: ``python scripts/gen_docs.py``
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"

#: Modules that get an API page. One line of prose per module, because the rest
#: comes from the docstring; keep the list ordered as it appears in the nav.
API_MODULES: list[tuple[str, str]] = [
    ("easyepi.bam2bigwig",
     "BAM to BigWig coverage, with the shift, normalisation and I/O decisions."),
    ("easyepi.coverage_parallel",
     "Chunked, process-parallel accumulation of per-base depth."),
    ("easyepi.assays",
     "The one assay vocabulary every command resolves its --assay against."),
    ("easyepi.peaks_cli",
     "Peak calling through MACS3 as a library, with the assay defaults."),
    ("easyepi.macs_options",
     "The MACS3 Namespace built from MACS3's own parser, plus the passthrough."),
    ("easyepi.tool_wrapper",
     "One way to wrap an external tool: modelled options, then verbatim passthrough."),
    ("easyepi.methylation_bam",
     "Per-cytosine methylation read directly from MM/ML or Bismax XM tags."),
    ("easyepi.dmr",
     "Two-group differential methylation with the region merge and its limitations."),
    ("easyepi.tf_annotate",
     "Known-motif annotation with exact PWM score thresholds."),
    ("easyepi.histone_states",
     "Multivariate-Bernoulli HMM for chromatin states."),
    ("easyepi.nucleosome_positioning",
     "Dyad calling from paired-end fragment midpoints."),
    ("easyepi.viz.genomeviews",
     "MA plot, peak-set overlap, TSS heatmap and locus tracks."),
    ("easyepi.viz.panels",
     "Multi-locus gene panels, UpSet and sample correlation."),
    ("easyepi.formats",
     "One definition of what a file extension means, shared by every scanner."),
    ("easyepi.errors",
     "Actionable messages for missing paths, dependencies and arguments."),
]


def _parser():
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from easyepi import cli
    return cli.build_parser()


def _subparsers(parser):
    for action in parser._actions:
        if hasattr(action, "choices") and action.choices:
            return action.choices
    return {}


def write_commands_index(parser) -> Path:
    """One table of every subcommand, generated from the parser."""
    choices = _subparsers(parser)
    lines = [
        "# Commands",
        "",
        f"`easyepi` exposes {len(choices)} subcommands. Each one reads files and writes",
        "files; none requires another to have run first.",
        "",
        "| Command | Purpose |",
        "| --- | --- |",
    ]
    for name, sub in choices.items():
        help_text = ""
        for action in sub._actions:
            if action.dest == "help":
                help_text = (action.help or "").replace("|", "\\|")
                break
        lines.append(f"| [`{name}`](../{name}.md) | {help_text} |" if False
                     else f"| `{name}` | {help_text} |")
    lines += [
        "",
        "Run `easyepi <command> --help` for the full option list of one command, or",
        "see [End-to-end examples](../EXAMPLES.md) for a complete sequence.",
        "",
        "## Getting the options into the docs",
        "",
        "This page is generated by `scripts/gen_docs.py` from the live parser, so the",
        "list cannot go stale. Per-command pages are on the left for the commands a",
        "beginner needs first; the rest are described by `--help` and by",
        "[USAGE.md](../USAGE.md).",
        "",
    ]
    path = DOCS / "commands" / "index.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_api_pages() -> list[Path]:
    written = []
    (DOCS / "api").mkdir(parents=True, exist_ok=True)
    for module, blurb in API_MODULES:
        page = DOCS / "api" / f"{module.split('.')[-1]}.md"
        page.write_text(
            "\n".join([
                f"# {module}",
                "",
                blurb,
                "",
                f"::: {module}",
                "",
            ]), encoding="utf-8")
        written.append(page)
    return written


def write_command_pages(parser) -> list[Path]:
    """Per-command page: its purpose, its real option list, and a minimal call."""
    from easyepi.cli import MINIMAL_EXAMPLE

    choices = _subparsers(parser)
    wanted = ["bam2bw", "qc", "peaks", "annotate", "tf-annotate", "dmr",
              "differential-peaks", "viz"]
    written = []
    (DOCS / "commands").mkdir(parents=True, exist_ok=True)
    for name in wanted:
        sub = choices.get(name)
        if sub is None:
            continue
        rows = []
        for action in sub._actions:
            if action.dest == "help":
                continue
            flags = ", ".join(f"`{o}`" for o in action.option_strings) or action.dest
            kind = "required" if getattr(action, "required", False) else "optional"
            default = "" if action.default in (None, False) else f"`{action.default}`"
            help_text = (action.help or "").replace("|", "\\|")
            rows.append(f"| {flags} | {kind} | {default} | {help_text} |")
        example = MINIMAL_EXAMPLE.get(name, "")
        page = DOCS / "commands" / f"{name}.md"
        page.write_text("\n".join([
            f"# easyepi {name}",
            "",
            "```bash",
            example,
            "```",
            "",
            "## Options",
            "",
            "| flag | required | default | description |",
            "| --- | --- | --- | --- |",
            *rows,
            "",
            "Generated from the live parser by `scripts/gen_docs.py`.",
            "",
        ]), encoding="utf-8")
        written.append(page)
    return written


def main() -> int:
    parser = _parser()
    paths = [write_commands_index(parser)]
    paths += write_api_pages()
    paths += write_command_pages(parser)
    for p in paths:
        print("wrote", p.relative_to(REPO))
    print(f"\n{len(paths)} page(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
