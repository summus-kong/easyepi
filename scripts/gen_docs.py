def _parser():
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from easyepi import cli
    return cli.build_parser()


def _subparsers(parser):
    for action in parser._actions:
        if hasattr(action, "choices") and action.choices:
            return action.choices
    return {}


def write_commands_index(parser) -> Path:
    """One table of every subcommand, generated from the parser."""
    choices = _subparsers(parser)
    lines = [
        "# Commands",
        "",
        # The count is generated, never typed: a hand-written "28 subcommands"
        # elsewhere had already drifted from the parser once, and a reader cannot
        # tell which page is authoritative.
        f"`easyepi` exposes {len(choices)} subcommands. Each one reads files and writes",
        "files; none requires another to have run first.",
        "",
        "| Command | Purpose |",
        "| --- | --- |",
    ]
    for name, sub in choices.items():
        help_text = ""
        for action in sub._actions:
            if action.dest == "help":
                help_text = (action.help or "").replace("|", "\\|")
                break
        lines.append(f"| [`{name}`](../{name}.md) | {help_text} |" if False
                     else f"| `{name}` | {help_text} |")
    lines += [
        "",
        "Run `easyepi <command> --help` for the full option list of one command, or",
        "see [End-to-end examples](../EXAMPLES.md) for a complete sequence.",
        "",
        "## Getting the options into the docs",
        "",
        "This page is generated by `scripts/gen_docs.py` from the live parser, so the",
        "list cannot go stale. Per-command pages are on the left for the commands a",
        "beginner needs first; the rest are described by `--help` and by",
        "[USAGE.md](../USAGE.md).",
        "",
    ]
    path = DOCS / "commands" / "index.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_api_pages() -> list[Path]:
    written = []
    (DOCS / "api").mkdir(parents=True, exist_ok=True)
    for module, blurb in API_MODULES:
        page = DOCS / "api" / f"{module.split('.')[-1]}.md"
        page.write_text(
            "\n".join([
                f"# {module}",
                "",
                blurb,
                "",
                f"::: {module}",
                "",
            ]), encoding="utf-8")
        written.append(page)
    return written


