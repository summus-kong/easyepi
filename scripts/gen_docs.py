"""Generate the MkDocs site skeleton from the real CLI.

Two reasons not to hand-write these pages:

1. **The command list must not drift.** ``commands/index.md`` is built by importing
   the parser, so a renamed flag or a new subcommand appears in the docs without
   anyone remembering to edit them.
2. **The API pages are one line each.** ``mkdocstrings`` pulls the reference out of
   the docstrings, so the only thing to generate is the stub pages that tell it which
   module to document.

Spec pages (``install.md``, ``quickstart.md``, assay pages) are written by hand --
they carry judgement that cannot be derived from code.

Run from the repository root: ``python scripts/gen_docs.py``
"""

